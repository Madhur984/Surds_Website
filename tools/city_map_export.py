# Project the SURDS city scene into image space for the website's interactive overlay.
#   blender -b tools/city_surds.blend --python tools/city_map_export.py
# Writes views/home/city-map.js: for the hero and network renders (2560x1440), the network
# routes (building -> hub, so packets flow inward), node points and a 2D outline per facility.
import bpy, math, json
from mathutils import Vector
from mathutils.geometry import convex_hull_2d
from bpy_extras.object_utils import world_to_camera_view

sc = bpy.context.scene
sc.render.resolution_x, sc.render.resolution_y = 2560, 1440
W, H = 2560, 1440
cam = bpy.data.objects["Cam"]; tgt = bpy.data.objects["CamTarget"]
VIEWS = {  # must match shoot_iso() calls in tools/city_look.py
    "hero":    dict(t=(10, 0, 6), az=225, el=33, scale=365, sx=-0.14, sy=0.02),
    "network": dict(t=(12, 6, 0), az=235, el=42, scale=345, sx=0.0, sy=0.085),
}
FAC_KEYS = ["dc", "dc", "clean", "energy", "health"]          # order of hubs_fac in city_look.py
GROUPS = {"dc": ("DataCenterA_", "DataCenterB_"), "clean": ("CleanRoom_",), "energy": ("Energy_",), "health": ("Hospital_",)}

def set_view(v):
    D = 600.0; a, e = math.radians(v["az"]), math.radians(v["el"]); t = v["t"]
    cam.data.type = "ORTHO"; cam.data.ortho_scale = v["scale"]; cam.data.shift_x, cam.data.shift_y = v["sx"], v["sy"]
    tgt.location = t
    cam.location = (t[0] + D * math.cos(e) * math.cos(a), t[1] + D * math.cos(e) * math.sin(a), t[2] + D * math.sin(e))
    bpy.context.view_layer.update()

def px(co):
    v = world_to_camera_view(sc, cam, Vector(co))
    return [round(v.x * W, 1), round((1 - v.y) * H, 1)]

def curve_pts(o):
    mw = o.matrix_world
    return [mw @ Vector(p.co[:3]) for p in o.data.splines[0].points]

def hull(objs, step=1):
    pts = []
    for o in objs:
        mw = o.matrix_world
        vs = o.data.vertices
        for i in range(0, len(vs), step): pts.append(px(mw @ vs[i].co))
    if len(pts) < 3: return []
    idx = convex_hull_2d(pts)
    return [pts[i] for i in idx]

core = [o for o in bpy.data.objects if o.type == "MESH" and len(o.data.polygons)
        and not any(c.name in ("Facilities", "Ground") for c in o.users_collection)
        and not o.name.startswith(("Hub", "FacHub", "FacNode", "Centre", "Tag_"))]
core += [o for o in bpy.data.objects if o.name.startswith("Rooftops_")]

out = {"w": W, "h": H}
for name, v in VIEWS.items():
    set_view(v)
    routes = []
    for o in bpy.data.objects:
        if o.type != "CURVE": continue
        if o.name.startswith("FacNet"):
            key = FAC_KEYS[int(o.name[6:])]
        elif o.name.startswith("Net") and o.name[3:].isdigit():
            key = "commercial"
        else: continue
        pts = curve_pts(o)[::-1]                                   # building -> hub
        beam = bpy.data.objects.get(("FacBeam" if key != "commercial" else "Beam") + o.name.split("Net")[-1])
        if beam: pts = [p for p in curve_pts(beam)[::-1]] + pts[1:]   # start at the roof node, drop down, run in
        routes.append({"k": key, "d": [px(p) for p in pts]})
    shapes = {k: [hull([o for o in bpy.data.objects if o.name.startswith(p) and o.type == "MESH"]) for p in pres]
              for k, pres in GROUPS.items()}
    shapes["commercial"] = [hull(core, 3)]
    centre = bpy.data.objects.get("Centre")
    out[name] = {"routes": routes, "shapes": shapes, "hub": px(centre.location) if centre else None}
    print("VIEW", name, len(routes), "routes")

js = "/* generated by tools/city_map_export.py from tools/city_surds.blend: do not edit by hand */\nwindow.CITY_MAP = " + json.dumps(out, separators=(",", ":")) + ";\n"
open(r"D:/Surds_Website/views/home/city-map.js", "w", encoding="utf-8").write(js)
print("WROTE city-map.js", len(js), "bytes")
